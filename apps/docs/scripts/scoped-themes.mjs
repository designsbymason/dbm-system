// Writes src/styles/generated/scoped-themes.css: the four token theme files with their
// `:root[data-theme="…"]` selector rewritten to `[data-theme-scope="…"]`, so one part of a page
// (the home page's theming section) can wear another brand or mode while the page keeps its own.
// The values come from @dbm-system/tokens unchanged; nothing is typed in here.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const themes = ["purple-light", "purple-dark", "emerald-light", "emerald-dark"];

const out = themes
  .map((theme) => {
    const css = readFileSync(require.resolve(`@dbm-system/tokens/css/${theme}.css`), "utf8");
    const selector = `:root[data-theme="${theme}"]`;
    if (!css.includes(selector)) throw new Error(`${theme}.css no longer uses the selector ${selector}`);
    return css.replaceAll(selector, `[data-theme-scope="${theme}"]`);
  })
  .join("\n");

const target = join(here, "../src/styles/generated/scoped-themes.css");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, `/* Generated by scripts/scoped-themes.mjs. Do not edit. */\n${out}`);
console.log(`scoped-themes: wrote ${themes.length} scoped themes`);
